function demoField(
  id: string,
  farmId: string,
  name: string,
  sw: [number, number],
  sizeM: [number, number],
  soilType: string,
  soilPh: number,
): Field {
  const geometry = rectanglePolygon(sw[0], sw[1], sizeM[0], sizeM[1]);
  return {
    id,
    farmId,
    name,
    geometry,
    areaM2: polygonAreaM2(geometry),
    soilType,
    soilPh,
    excludedZones: null,
  };
}

